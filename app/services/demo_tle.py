def _with_checksum(line: str) -> str:
    core = line.rstrip()[:68].ljust(68)
    return core + str(_compute_checksum(core + "0"))


def demo_tle_text() -> str:
    blocks = []
    for name, line1, line2 in _RAW_DEMO_TLES:
        blocks.append(f"{name}\n{_with_checksum(line1)}\n{_with_checksum(line2)}")
    return "\n\n".join(blocks) + "\n"
